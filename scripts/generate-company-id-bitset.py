#!/usr/bin/env python3
import argparse
import hashlib
import re
from pathlib import Path


REVISION = "90e83ed1e959291dc903e604d3ec8c3d4ebc8a34"
SOURCE_SHA256 = "91bc95ac03cd72b2742e28934f4f48a1202f69ce899cecf74dce072125469d5d"
SOURCE_URL = (
    "https://bitbucket.org/bluetooth-SIG/public/src/"
    f"{REVISION}/assigned_numbers/company_identifiers/"
    "company_identifiers.yaml"
)
VALUE_PATTERN = re.compile(r"^\s*-\s+value:\s+0x([0-9a-fA-F]{4})\s*$", re.MULTILINE)


def render_header(source: bytes) -> str:
    digest = hashlib.sha256(source).hexdigest()
    if digest != SOURCE_SHA256:
        raise ValueError(
            f"source SHA-256 {digest} does not match pinned snapshot {SOURCE_SHA256}"
        )
    text = source.decode("utf-8")
    values = [int(match, 16) for match in VALUE_PATTERN.findall(text)]
    if not values:
        raise ValueError("no company identifiers found")
    if len(values) != len(set(values)):
        raise ValueError("duplicate company identifier found")

    maximum = max(values)
    bits = bytearray(maximum // 8 + 1)
    for value in values:
        bits[value // 8] |= 1 << (value % 8)

    rows = []
    for offset in range(0, len(bits), 12):
        row = ", ".join(f"0x{value:02x}" for value in bits[offset:offset + 12])
        rows.append(f"    {row},")

    return "\n".join([
        "#ifndef AMULET_BLE_COMPANY_IDS_GENERATED_H",
        "#define AMULET_BLE_COMPANY_IDS_GENERATED_H",
        "",
        "#include <stdint.h>",
        "",
        "// Generated by scripts/generate-company-id-bitset.py.",
        f"// Source revision: {REVISION}",
        f"// Source: {SOURCE_URL}",
        f"// Source SHA-256: {digest}",
        f"#define AMULET_BLE_ASSIGNED_COMPANY_ID_MAX UINT16_C(0x{maximum:04x})",
        "",
        "static const uint8_t AMULET_BLE_ASSIGNED_COMPANY_ID_BITS[] = {",
        *rows,
        "};",
        "",
        "#endif",
        "",
    ])


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate the pinned Bluetooth SIG company-ID lookup"
    )
    parser.add_argument("source", type=Path, help="company_identifiers.yaml")
    parser.add_argument("output", type=Path, help="generated C header")
    args = parser.parse_args()
    args.output.write_text(render_header(args.source.read_bytes()), encoding="ascii")


if __name__ == "__main__":
    main()
